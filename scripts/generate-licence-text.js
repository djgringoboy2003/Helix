#!/usr/bin/env node
// Bundles the licence documents into the app.
//
// Helix is AGPL-3.0-or-later. `CLAUDE.md` requires the licence files,
// copyright notices, third-party notices and attribution to be kept, and an app
// that only links to them on GitHub does not convey them to someone holding the
// APK offline. So the text is compiled into `constants/licenceText.ts`.
//
// The repository files stay the source of truth: this only copies them, and
// `tests/unit/licenceText.test.js` regenerates the module in memory and fails
// if it no longer matches. Editing LICENSE without re-running this is therefore
// caught by the suite rather than shipping a stale notice.
//
// Run: node scripts/generate-licence-text.js

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

/** Order matters: it is the order the screen shows them in. */
const DOCUMENTS = [
  { key: 'licence', title: 'Licence — AGPL-3.0-or-later', file: 'LICENSE' },
  { key: 'attribution', title: 'Attribution', file: 'ATTRIBUTION.md' },
  { key: 'thirdParty', title: 'Third-party notices', file: 'THIRD_PARTY_NOTICES.md' },
];

function readDocument(file) {
  // Newlines are normalised so a checkout with CRLF endings produces the same
  // module as one with LF, and the drift test does not fail on line endings.
  return fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/\r\n/g, '\n').trimEnd();
}

function buildModule() {
  const entries = DOCUMENTS.map(
    (doc) =>
      `  {\n` +
      `    key: ${JSON.stringify(doc.key)},\n` +
      `    title: ${JSON.stringify(doc.title)},\n` +
      `    sourceFile: ${JSON.stringify(doc.file)},\n` +
      `    text: ${JSON.stringify(readDocument(doc.file))},\n` +
      `  },`
  ).join('\n');

  return `// GENERATED by scripts/generate-licence-text.js — do not edit by hand.
//
// Edit LICENSE, ATTRIBUTION.md or THIRD_PARTY_NOTICES.md and re-run the
// generator. \`tests/unit/licenceText.test.js\` fails if this file drifts from
// them, so a stale notice cannot ship unnoticed.

export interface LicenceDocument {
  key: string;
  title: string;
  /** Path in the repository, shown so the text can be checked against source. */
  sourceFile: string;
  text: string;
}

export const LICENCE_DOCUMENTS: LicenceDocument[] = [
${entries}
];
`;
}

const output = buildModule();

if (require.main === module) {
  const target = path.join(ROOT, 'constants', 'licenceText.ts');
  fs.writeFileSync(target, output, 'utf8');
  const bytes = Buffer.byteLength(output, 'utf8');
  console.log(`wrote constants/licenceText.ts (${(bytes / 1024).toFixed(1)} KB)`);
}

module.exports = { buildModule, DOCUMENTS };
